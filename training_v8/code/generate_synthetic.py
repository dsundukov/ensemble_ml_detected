VARIANTS = {"C03": 3, "B02": 3, "B06": 3, "C08": 3, "C09": 3, "B07": 3, "C07": 3, "C05": 4, "B01": 3,
            "A04": 4, "A05": 4, "A11": 4, "A06": 4}
DEFAULT_VARIANTS = 2


def skeleton(text: str) -> str:
    return " ".join(re.sub(r"[\W\d_]+", " ", text.lower()).split())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/ru_synthetic_domain.csv")
    ap.add_argument("--check", nargs="*", default=[],
                    help="CSV, с которыми не должно быть пересечений (контрольная выборка, выборка для порога)")
    ap.add_argument("--max-sim", type=float, default=0.75, help="порог сходства для удаления близких строк")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    rng = random.Random(args.seed)

    rows = []
    for code, label, templates in T:
        for ti, tpl in enumerate(templates):
            k = VARIANTS.get(code, DEFAULT_VARIANTS) if "{" in tpl else 1
            seen = set()
            for _ in range(k * 5):
                if len(seen) >= k:
                    break
                text = fill(tpl, rng)
                if text in seen:
                    continue
                seen.add(text)
                rows.append({"text": text, "label": label, "group": f"SYN-{code}-{ti:02d}",
                             "source": SOURCE, "test_id": f"SYN-{code}-{ti:02d}-{len(seen)}",
                             "code": code, "category": CATEGORY[code], "unanimous": ""})
    df = pd.DataFrame(rows).drop_duplicates("text")
    print(f"Сгенерировано: {len(df)} строк (атак {int(df.label.sum())}, безобидных {int((df.label == 0).sum())})")

    if args.check:
        ref = pd.concat([pd.read_csv(p) for p in args.check])["text"].astype(str).tolist()
        ref_sk = {skeleton(t) for t in ref}
        ref_low = [t.lower() for t in ref]

        def leaks(t):
            if skeleton(t) in ref_sk:
                return True
            tl = t.lower()
            return any(difflib.SequenceMatcher(None, tl, r).ratio() >= args.max_sim for r in ref_low)

        mask = df["text"].map(leaks)
        print(f"Удалено из-за сходства с проверочными выборками (порог {args.max_sim}): {int(mask.sum())}")
        df = df[~mask]

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.out, index=False)
    print(f"Сохранено: {args.out} — {len(df)} строк (атак {int(df.label.sum())}, "
          f"безобидных {int((df.label == 0).sum())}, шаблонов-групп {df.group.nunique()})")
    print(df.groupby(["label", "code"]).size().unstack(0, fill_value=0).to_string())


if __name__ == "__main__":
    main()
